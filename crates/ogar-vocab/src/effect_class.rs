//! `effect_class` — the shared classification of what a behaviour DOES, so that
//! a population fold is never confused with a write.
//!
//! The vocabulary is taken from `zammad-rs`,
//! `crates/rails-f000/src/effects.rs` (the `EffectClass` enum at lines 16-26,
//! the refusal and deferral table of `classify_callback` at lines 61-88, the
//! class decision `classify_class` at lines 90-114, `classify_condition` at
//! lines 116-125), whose module doc states the rule this module exists to
//! keep:
//!
//! > An F000 word is a fold over a population. It never authorizes a write, an
//! > ordered lifecycle step, or a commit-stage effect.
//!
//! The same eight classes are used by OGAR, odoo-rs, zammad-rs and HIRO, so
//! that a behaviour found in any of them is answered the same way. The
//! hand-off is: queries and derived values may be a DT64 `MethodBinding` with
//! F000 (`0xFFFF::0xF000` polyfill) effects; everything else is never F000 and
//! is handed to the gate (`commit_via`) as an `ActionInvocation`. See
//! `docs/SHARED-DO-DESIGN.md`.
//!
//! This module has no lance-graph dependency (`ogar-vocab` stays free of it):
//! it classifies, it does not lower and it does not decide an admission.
//! Admission is a `Verdict` in zammad-rs (`transpose.rs:70-98`) and needs the
//! lowered body, which an [`ActionDef`] does not carry.
//!
//! # Deciding a class: [`classify`]
//!
//! An [`ActionDef`] is a name-level declaration: its effect facts are `reads`,
//! `writes`, `calls`, `raises` (names only, no values), the typed `kausal`
//! trigger, `default_temporal`, and `on_enter`. [`classify`] reads only those.
//! The rule, first match wins (mirroring zammad-rs `classify_class`, where the
//! phase is the lifecycle event and `Binding` is the kind of body):
//!
//! 1. `on_enter` is set, or `default_temporal` is `OnCommit`, or `kausal` is a
//!    `LifecycleTrigger` of `after_commit` / `after_rollback`:
//!    [`EffectClass::TransactionEffect`]. The effect runs at or after the
//!    commit crossing, ordered by it.
//! 2. `kausal` is `Constrains` (declared by `ogar-vocab` to be "semantically a
//!    VALIDATION"): [`EffectClass::Validation`].
//! 3. The def mutates (`writes` or `calls` is non-empty; `calls` is by its own
//!    doc "lifecycle-mutator dispatch"): [`EffectClass::FieldTransform`] when
//!    its trigger is record-local (`Depends`, `Onchange`, or a `before_*` /
//!    `after_initialize` lifecycle event), else [`EffectClass::LifecycleWrite`].
//! 4. `kausal` is a `LifecycleTrigger` of `validate` / `*validation`:
//!    [`EffectClass::Validation`].
//! 5. `kausal` is `External` (an external cause, RPC or HTTP, with nothing
//!    declared about the body): [`EffectClass::ExternalHost`]. The body is
//!    outside what the lens can address.
//! 6. Anything else: [`EffectClass::Unresolved`]. A def that names no
//!    evidence is never guessed into a class.
//!
//! What [`classify`] never returns, and why: [`EffectClass::PurePredicateCondition`]
//! classifies an `if:` / `unless:` condition (zammad-rs `classify_condition`),
//! and no [`ActionDef`] field carries a condition expression;
//! [`EffectClass::FrameworkGenerated`] needs a marker that the framework, not
//! the source, generated the callback, and no field carries one. `raises`
//! alone is not evidence of a class (a button action raises `UserError` too),
//! and neither is `ModalSpec::Atomic` (a retry/rollback mode, not a commit
//! stage).

use crate::{ActionDef, KausalSpec, TemporalSpec};

/// What a behaviour is known to do, and so what may and may not be done with
/// it. The classes and their meanings are zammad-rs
/// `rails-f000/src/effects.rs:16-26`; the doc of each states the answer
/// zammad-rs gives it (`effects.rs:69-86`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[non_exhaustive]
pub enum EffectClass {
    /// Generated by the framework rather than written in the source
    /// (ActiveRecord's own callbacks). Refused: "ordered by the save
    /// pipeline, per record".
    FrameworkGenerated,
    /// A pure condition (`if:` / `unless:`) over one record. It writes
    /// nothing, but it is a per-record scalar and not a population fold, so
    /// zammad-rs defers it ("per-record scalar, not a population fold"). The
    /// only class that is not a write.
    PurePredicateCondition,
    /// Writes a field of the record being saved (a `before_*` or
    /// `after_initialize` step; here also a record-local `Depends` /
    /// `Onchange` computation that assigns). Refused: "writes a field of the
    /// record being saved; a fold never writes".
    FieldTransform,
    /// Adds errors to one record in chain order (`validate`, `Constrains`).
    /// Refused: "validation adds errors to one record in chain order".
    Validation,
    /// Writes during an ordered lifecycle step, including a call of a
    /// lifecycle mutator. Refused: "writes during an ordered lifecycle step;
    /// a fold never writes".
    LifecycleWrite,
    /// A commit-stage effect (`after_commit`, `after_rollback`, the Rubicon
    /// crossing `on_enter`). Refused: "runs after the transaction, ordered by
    /// it; a population fold is neither".
    TransactionEffect,
    /// A body bound to a host the lens cannot address (an external executor,
    /// an RPC or HTTP cause). Refused: "body is host-bound, outside what the
    /// lens can address".
    ExternalHost,
    /// Not enough is known to decide. Deferred, never guessed: the body
    /// could not be lowered, or writes nothing the declaration shows but
    /// still runs per record in lifecycle order.
    Unresolved,
}

impl EffectClass {
    /// Every class, in declaration order.
    pub const ALL: [EffectClass; 8] = [
        EffectClass::FrameworkGenerated,
        EffectClass::PurePredicateCondition,
        EffectClass::FieldTransform,
        EffectClass::Validation,
        EffectClass::LifecycleWrite,
        EffectClass::TransactionEffect,
        EffectClass::ExternalHost,
        EffectClass::Unresolved,
    ];

    /// Whether a method of this class may carry F000 effects at all.
    ///
    /// True only for [`EffectClass::PurePredicateCondition`]: it is the one
    /// class that is not a write, an ordered lifecycle step or a commit-stage
    /// effect. This is a necessary condition, not an admission: zammad-rs still
    /// defers such a condition as a per-record scalar, and a population fold
    /// is admitted only by a `Verdict::Alias` / `Compose` over the lowered
    /// body (`transpose.rs:84-86`), which this crate cannot compute.
    ///
    /// [`EffectClass::FieldTransform`] is deliberately NOT admissible: in
    /// zammad-rs it is a refusal (`effects.rs:78`). A derived value
    /// (an Odoo `_compute_`) that is a pure fold is lowered as a query on its
    /// own path, not by classifying its assigning method as a field
    /// transform; see `docs/SHARED-DO-DESIGN.md`.
    #[must_use]
    pub const fn is_f000_admissible(self) -> bool {
        matches!(self, EffectClass::PurePredicateCondition)
    }

    /// Whether the behaviour must be handed to the gate (`commit_via`) as an
    /// `ActionInvocation` rather than run as a DT64 method.
    ///
    /// The complement of [`EffectClass::is_f000_admissible`], so
    /// [`EffectClass::Unresolved`] fails closed: an unknown behaviour never
    /// skips the gate.
    #[must_use]
    pub const fn requires_gate(self) -> bool {
        !self.is_f000_admissible()
    }

    /// Whether the class writes, orders or commits (the three things an F000
    /// word never authorizes). False for [`EffectClass::PurePredicateCondition`]
    /// and for [`EffectClass::Unresolved`], whose behaviour is not known.
    #[must_use]
    pub const fn is_effectful(self) -> bool {
        !matches!(
            self,
            EffectClass::PurePredicateCondition | EffectClass::Unresolved
        )
    }

    /// A stable lower-case name for reports.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            EffectClass::FrameworkGenerated => "framework_generated",
            EffectClass::PurePredicateCondition => "pure_predicate_condition",
            EffectClass::FieldTransform => "field_transform",
            EffectClass::Validation => "validation",
            EffectClass::LifecycleWrite => "lifecycle_write",
            EffectClass::TransactionEffect => "transaction_effect",
            EffectClass::ExternalHost => "external_host",
            EffectClass::Unresolved => "unresolved",
        }
    }
}

/// The lifecycle event of a def's trigger, or `""` when it has none.
fn phase(def: &ActionDef) -> &str {
    match &def.kausal {
        Some(KausalSpec::LifecycleTrigger { event }) => event.as_str(),
        _ => "",
    }
}

/// Classify one [`ActionDef`] from the evidence it carries. See the module doc
/// for the rule; a def that names no evidence is [`EffectClass::Unresolved`].
#[must_use]
pub fn classify(def: &ActionDef) -> EffectClass {
    let phase = phase(def);
    if def.on_enter.is_some()
        || def.default_temporal == TemporalSpec::OnCommit
        || matches!(phase, "after_commit" | "after_rollback")
    {
        return EffectClass::TransactionEffect;
    }
    if matches!(def.kausal, Some(KausalSpec::Constrains { .. })) {
        return EffectClass::Validation;
    }
    if !def.writes.is_empty() || !def.calls.is_empty() {
        let record_local = matches!(
            def.kausal,
            Some(KausalSpec::Depends { .. } | KausalSpec::Onchange { .. })
        ) || phase.starts_with("before_")
            || phase == "after_initialize";
        return if record_local {
            EffectClass::FieldTransform
        } else {
            EffectClass::LifecycleWrite
        };
    }
    if phase == "validate" || phase.ends_with("validation") {
        return EffectClass::Validation;
    }
    if matches!(def.kausal, Some(KausalSpec::External)) {
        return EffectClass::ExternalHost;
    }
    EffectClass::Unresolved
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::EnterEffect;

    fn def() -> ActionDef {
        ActionDef::new("ns/c::action_def::x", "x", "ns/c")
    }

    fn with(kausal: KausalSpec) -> ActionDef {
        let mut d = def();
        d.kausal = Some(kausal);
        d
    }

    fn lifecycle(event: &str) -> ActionDef {
        with(KausalSpec::LifecycleTrigger {
            event: event.into(),
        })
    }

    #[test]
    fn a_bare_def_is_unresolved_never_guessed() {
        assert_eq!(classify(&def()), EffectClass::Unresolved);
        // Reads, raises and a state guard are not evidence of an effect class.
        let mut d = with(KausalSpec::StateGuard {
            guard_field: "state".into(),
            guard_values: vec!["1".into()],
        });
        d.reads = vec!["a".into()];
        d.raises = vec!["UserError".into()];
        assert_eq!(classify(&d), EffectClass::Unresolved);
        assert_eq!(
            classify(&with(KausalSpec::ContextDepends {
                keys: vec!["lang".into()]
            })),
            EffectClass::Unresolved
        );
    }

    #[test]
    fn an_external_cause_with_no_body_is_external_host() {
        assert_eq!(
            classify(&with(KausalSpec::External)),
            EffectClass::ExternalHost
        );
    }

    #[test]
    fn writes_win_over_an_external_cause() {
        let mut d = with(KausalSpec::External);
        d.writes = vec!["state".into()];
        assert_eq!(classify(&d), EffectClass::LifecycleWrite);
    }

    #[test]
    fn commit_stage_evidence_is_a_transaction_effect() {
        assert_eq!(
            classify(&lifecycle("after_commit")),
            EffectClass::TransactionEffect
        );
        assert_eq!(
            classify(&lifecycle("after_rollback")),
            EffectClass::TransactionEffect
        );
        let mut d = with(KausalSpec::External);
        d.on_enter = Some(EnterEffect::transition("state", "1"));
        assert_eq!(classify(&d), EffectClass::TransactionEffect);
        let mut d = def();
        d.default_temporal = TemporalSpec::OnCommit;
        assert_eq!(classify(&d), EffectClass::TransactionEffect);
        // It outranks a write.
        let mut d = lifecycle("after_commit");
        d.writes = vec!["a".into()];
        assert_eq!(classify(&d), EffectClass::TransactionEffect);
    }

    #[test]
    fn a_constrains_is_a_validation_even_when_it_names_writes() {
        let mut d = with(KausalSpec::Constrains {
            paths: vec!["a".into()],
        });
        assert_eq!(classify(&d), EffectClass::Validation);
        d.writes = vec!["a".into()];
        assert_eq!(classify(&d), EffectClass::Validation);
        assert_eq!(classify(&lifecycle("validate")), EffectClass::Validation);
        assert_eq!(
            classify(&lifecycle("before_validation")),
            EffectClass::Validation
        );
    }

    #[test]
    fn a_write_is_a_field_transform_when_record_local_else_a_lifecycle_write() {
        let write = |mut d: ActionDef| {
            d.writes = vec!["a".into()];
            classify(&d)
        };
        assert_eq!(write(lifecycle("before_save")), EffectClass::FieldTransform);
        assert_eq!(
            write(lifecycle("after_initialize")),
            EffectClass::FieldTransform
        );
        assert_eq!(
            write(with(KausalSpec::Depends {
                paths: vec!["b".into()]
            })),
            EffectClass::FieldTransform
        );
        assert_eq!(
            write(with(KausalSpec::Onchange {
                paths: vec!["b".into()]
            })),
            EffectClass::FieldTransform
        );
        assert_eq!(
            write(lifecycle("after_create")),
            EffectClass::LifecycleWrite
        );
        assert_eq!(write(def()), EffectClass::LifecycleWrite);
    }

    #[test]
    fn a_lifecycle_mutator_call_counts_as_a_write() {
        let mut d = lifecycle("after_create");
        d.calls = vec!["self.write".into()];
        assert_eq!(classify(&d), EffectClass::LifecycleWrite);
    }

    #[test]
    fn a_non_writing_lifecycle_step_is_unresolved() {
        assert_eq!(
            classify(&lifecycle("after_create")),
            EffectClass::Unresolved
        );
        assert_eq!(
            classify(&with(KausalSpec::Depends {
                paths: vec!["b".into()]
            })),
            EffectClass::Unresolved
        );
    }

    #[test]
    fn only_a_pure_condition_may_carry_f000_and_everything_else_needs_the_gate() {
        for c in EffectClass::ALL {
            assert_eq!(
                c.is_f000_admissible(),
                c == EffectClass::PurePredicateCondition,
                "{c:?}"
            );
            assert_eq!(c.requires_gate(), !c.is_f000_admissible(), "{c:?}");
        }
        // FieldTransform is a write refusal in zammad-rs, not an F000 class.
        assert!(!EffectClass::FieldTransform.is_f000_admissible());
        // Unknown fails closed.
        assert!(EffectClass::Unresolved.requires_gate());
        assert!(!EffectClass::Unresolved.is_effectful());
    }

    #[test]
    fn census_of_the_authoritative_tables() {
        let mut dist = std::collections::BTreeMap::new();
        for t in crate::capability_registry::domain_tables() {
            for d in (t.actions)() {
                *dist
                    .entry((t.domain, classify(&d).name()))
                    .or_insert(0usize) += 1;
            }
        }
        // geo 6 + healthcare 20 + erp 7 are name-only External defs: no body
        // evidence, so ExternalHost. ocr 14 + document 3 name `writes` (their
        // declared output names), so LifecycleWrite. Nothing is
        // F000-admissible and nothing is Unresolved.
        let want: std::collections::BTreeMap<(&str, &str), usize> = [
            (("document", "lifecycle_write"), 3),
            (("erp", "external_host"), 7),
            (("geo", "external_host"), 6),
            (("healthcare", "external_host"), 20),
            (("ocr", "lifecycle_write"), 14),
        ]
        .into_iter()
        .collect();
        assert_eq!(dist, want);
    }

    #[test]
    fn names_are_distinct() {
        let mut names: Vec<&str> = EffectClass::ALL.iter().map(|c| c.name()).collect();
        names.sort_unstable();
        names.dedup();
        assert_eq!(names.len(), 8);
    }
}
